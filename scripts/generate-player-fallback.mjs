import { readFile, writeFile } from "node:fs/promises";

const sourceUrl = new URL("../assets/data/players.json", import.meta.url);
const outputUrl = new URL("../assets/data/players-fallback.js", import.meta.url);
const players = JSON.parse(await readFile(sourceUrl, "utf8"));
const output =
  `// Generated from players.json. Do not edit this file directly.\n` +
  `window.PLAYER_DATA = ${JSON.stringify(players, null, 2)};\n`;

await writeFile(outputUrl, output, "utf8");
